import { test, expect } from '@playwright/test'

test('health drops stale success on failure and recovers despite other API failures', async ({ page }) => {
  let unavailable = false
  await page.route('**/api/health', async route => {
    if (unavailable) return route.fulfill({ status: 503, json: { error: 'Memória temporariamente inacessível.' } })
    const response = await route.fetch()
    const health = await response.json()
    await route.fulfill({ json: { ...health, status: 'healthy', issues: [], daemon: { running: true, semantic: 'ready' } } })
  })
  await page.goto('/#health')
  await expect(page.getByText('Disponível', { exact: true })).toBeVisible()
  await expect(page.getByText('Captura automática configurada', { exact: true })).toBeVisible()
  unavailable = true
  await page.route('**/api/learning', route => route.fulfill({ status: 503, json: { error: 'Armazenamento indisponível.' } }))
  await page.getByRole('button', { name: 'Atualizar dados', exact: true }).click()
  await expect(page.getByText('Memória temporariamente inacessível.', { exact: false })).toBeVisible()
  await expect(page.getByText('Disponível', { exact: true })).not.toBeVisible()
  await expect(page.getByText('Conferindo memória e backups…', { exact: true })).not.toBeVisible()
  unavailable = false
  await page.getByRole('button', { name: 'Atualizar estado', exact: true }).click()
  await expect(page.getByText('Disponível', { exact: true })).toBeVisible()
  await expect(page.getByText('Memória temporariamente inacessível.', { exact: false })).not.toBeVisible()
})

